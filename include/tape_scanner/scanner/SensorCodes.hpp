#pragma once

#include <opencv2/core.hpp>
#include <vector>

/**
 * Покадровый шаг после распаковки.
 * Возвращает те же отсчёты CV_16UC1. Кривая нелинейности не применяется:
 * тёмный уровень не вычитается и диапазон не растягивается до 65535.
 * Пустой кадр возвращается как есть. Чужой тип — invalid_argument.
 */
cv::Mat RetainRawSensorCodes(const cv::Mat &sensor_codes);

/**
 * Слияние экспозиций линейного сенсора без кривой отклика.
 * По пикселю: сумма кодов / сумма экспозиций среди отсчётов ниже 4095.
 * Если живых отсчётов нет, берётся код кратчайшей экспозиции, делённый на неё.
 * Результат CV_32FC1: код на единицу запрошенной экспозиции.
 * Кадры — непустые CV_16UC1 одного размера, экспозиции строго положительные.
 */
cv::Mat MergeLinearExposures(const std::vector<cv::Mat> &frames,
                             const std::vector<float> &exposure_us);
